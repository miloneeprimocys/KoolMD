"use client";

import React, { useMemo, useState } from "react";
import { useRouter, useSearchParams } from "next/navigation";

import Breadcrumb from "@/components/Breadcrumb";
import AddButton from "@/components/Addbutton";
import ImportButton from "@/components/ImportButton";
import Tags from "@/components/Tags";
import SignupField from "@/components/SignupField";
import SignupDropdown from "@/components/SignupDropdown";
import {
  ModalDateField,
  ModalTextarea,
  OptLabel,
  ReqLabel,
  toOptions,
  todayISO,
} from "@/components/Modalshell";

const LIST_ROUTE = "/manage/refunds";

/* ---------- Static data (replace with API data later) ---------- */
type RefundableInvoice = {
  id: string;
  patient: string;
  amount: number;
  paid: number;
  previousRefunds: number;
};

const INVOICES: RefundableInvoice[] = [
  { id: "INV-0996", patient: "Sarah Lee", amount: 320, paid: 320, previousRefunds: 0 },
  { id: "INV-2024-1045", patient: "Emily Carter", amount: 125, paid: 125, previousRefunds: 0 },
  { id: "INV-2024-1044", patient: "Michael Brown", amount: 250, paid: 250, previousRefunds: 50 },
  { id: "INV-2024-1043", patient: "Sophia Williams", amount: 75, paid: 75, previousRefunds: 0 },
];

const REFUND_METHODS = ["Credit Card", "ACH", "Online (Wallet)", "Cash"];

const REASONS = [
  "Appointment cancelled",
  "Overpayment",
  "Service not rendered",
  "Duplicate payment",
  "Payment processing error",
  "Insurance adjustment",
  "Patient request",
  "Billing error",
  "Other",
];

const NEXT_REFUND_ID = "REF-2024-1025"; // generated by the backend later
const PROCESSED_BY = "System Administrator"; // current logged-in user

const money = (n: number) => `$${n.toFixed(2)}`;

type Errors = { invoice?: string; amount?: string; method?: string; reason?: string };

/* ---------- Small row for the invoice card ---------- */
const InfoRow = ({
  label,
  value,
  accent = false,
}: {
  label: string;
  value: React.ReactNode;
  accent?: boolean;
}) => (
  <div className="flex items-center justify-between gap-3 text-sm">
    <dt className="text-body">{label}</dt>
    <dd className={`font-semibold ${accent ? "text-primary" : "text-heading"}`}>{value}</dd>
  </div>
);

/* ---------- Page ---------- */
const CreateRefund = () => {
  const router = useRouter();
  const preselected = useSearchParams().get("invoice");

  const [invoiceId, setInvoiceId] = useState(
    INVOICES.some((i) => i.id === preselected) ? (preselected as string) : INVOICES[0].id,
  );
  const [refundDate, setRefundDate] = useState(todayISO());
  const [amount, setAmount] = useState("");
  const [method, setMethod] = useState(REFUND_METHODS[0]);
  const [reason, setReason] = useState(REASONS[3]);
  const [notes, setNotes] = useState("");
  const [errors, setErrors] = useState<Errors>({});

  const invoice = useMemo(() => INVOICES.find((i) => i.id === invoiceId) ?? INVOICES[0], [invoiceId]);
  const refundable = Math.max(invoice.paid - invoice.previousRefunds, 0);

  const handleInvoiceChange = (id: string) => {
    setInvoiceId(id);
    setAmount("");
    setErrors({});
  };

  const handleSubmit = () => {
    const next: Errors = {};
    const value = Number(amount);
    if (!(value > 0)) next.amount = "Enter a refund amount";
    else if (value > refundable) next.amount = `Cannot exceed ${money(refundable)}`;
    if (!method) next.method = "Select a refund method";
    if (!reason) next.reason = "Select a reason";
    setErrors(next);
    if (Object.keys(next).length) return;

    console.log("create refund", {
      refundId: NEXT_REFUND_ID,
      invoiceId: invoice.id,
      patient: invoice.patient,
      refundDate,
      amount: value,
      method,
      reason,
      notes,
      processedBy: PROCESSED_BY,
      status: "Pending",
    }); // TODO: call your API here
    router.push(LIST_ROUTE);
  };

  return (
    <div className="mx-auto w-full max-w-[1600px] space-y-4 sm:space-y-5">
      <Breadcrumb
        items={[
          { label: "Billing", href: "/payment/payment-gateway" },
          { label: "Refunds", href: LIST_ROUTE },
          { label: "Create Refund" },
        ]}
      />

      {/* Title + actions */}
      <div className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
        <div>
          <h2 className="text-lg font-semibold text-heading sm:text-xl 2xl:text-2xl">Create Refund</h2>
          <p className="mt-0.5 text-sm text-body">Process a refund against a paid invoice.</p>
        </div>
        <div className="flex items-center gap-3">
          <ImportButton text="Cancel" icon={null} onClick={() => router.push(LIST_ROUTE)} />
          <AddButton text="Create" icon={null} onClick={handleSubmit} className="whitespace-nowrap" />
        </div>
      </div>

      <div className="grid items-start gap-4 sm:gap-5 lg:grid-cols-[340px_minmax(0,1fr)]">
        {/* ================= LEFT: Invoice details ================= */}
        <section className="min-w-0 rounded-[14px] border border-border bg-card p-4 sm:p-6">
          <h3 className="text-base font-semibold text-heading">Invoice Details</h3>

          <div className="mt-4">
            <SignupDropdown
              name="refundInvoice"
              label={<ReqLabel>Original Invoice</ReqLabel>}
              value={invoiceId}
              onChange={handleInvoiceChange}
              options={INVOICES.map((i) => ({ value: i.id, label: `${i.id} — ${i.patient}` }))}
            />
          </div>

          <dl className="mt-5 space-y-3.5">
            <InfoRow label="Invoice #" value={invoice.id} accent />
            <InfoRow label="Patient" value={invoice.patient} accent />
            <InfoRow label="Invoice Amount" value={money(invoice.amount)} />
            <InfoRow label="Amount Paid" value={money(invoice.paid)} />
            <InfoRow label="Previous Refunds" value={money(invoice.previousRefunds)} />
            <InfoRow label="Refundable Amount" value={money(refundable)} />
          </dl>
        </section>

        {/* ================= RIGHT: Refund details ================= */}
        <section className="min-w-0 rounded-[14px] border border-border bg-card p-4 sm:p-6">
          <div className="flex items-start justify-between gap-3">
            <h3 className="text-base font-semibold text-heading">Refund Details</h3>
            <div className="flex items-center gap-2 text-xs text-body">
              <span>{NEXT_REFUND_ID}</span>
              <Tags text="Pending" tone="warning" size="xs" />
            </div>
          </div>

          <div className="mt-5 grid gap-x-4 gap-y-4 sm:grid-cols-2">
            <ModalDateField
              id="refund-date"
              label={<ReqLabel>Refund Date</ReqLabel>}
              value={refundDate}
              onChange={setRefundDate}
            />

            <SignupField
              name="refundAmount"
              type="number"
              label={<ReqLabel>Amount ($)</ReqLabel>}
              placeholder="0.00"
              value={amount}
              error={errors.amount}
              onChange={(e) => setAmount(e.target.value)}
            />

            <SignupDropdown
              name="refundMethod"
              label={<ReqLabel>Refund Method</ReqLabel>}
              value={method}
              onChange={setMethod}
              options={toOptions(REFUND_METHODS)}
            />

            <SignupDropdown
              name="refundReason"
              label={<ReqLabel>Reason</ReqLabel>}
              value={reason}
              onChange={setReason}
              options={toOptions(REASONS)}
            />

            <div className="sm:col-span-2">
              <ModalTextarea
                id="refund-notes"
                label={<OptLabel>Notes</OptLabel>}
                placeholder="Add notes (optional)"
                value={notes}
                onChange={setNotes}
                maxLength={500}
              />
            </div>

            <div className="sm:col-span-2">
              <p className="mb-2 text-sm font-medium text-label">Processed By</p>
              <div className="flex h-12 items-center rounded-xl border border-border bg-primary/[0.06] px-4 text-sm font-medium text-heading">
                {PROCESSED_BY}
              </div>
            </div>
          </div>
        </section>
      </div>
    </div>
  );
};

export default CreateRefund;
